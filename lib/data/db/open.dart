import 'dart:io';
import 'dart:math';

import 'package:drift/drift.dart';
import 'package:drift/native.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';

import 'database.dart';

/// Result of trying to open the encrypted database at startup.
sealed class OpenResult {
  const OpenResult();
}

class DbOpened extends OpenResult {
  const DbOpened(this.db);
  final AppDatabase db;
}

/// The database file exists but its key is missing or wrong.
/// Typical cause on iPhone: the app was re-signed with a different Apple ID,
/// so the Keychain entry holding the key isn't visible any more.
class DbKeyProblem extends OpenResult {
  const DbKeyProblem(this.file, {required this.keyMissing});
  final File file;
  final bool keyMissing;
}

/// Anything else (including encryption support missing from the build).
class DbFailed extends OpenResult {
  const DbFailed(this.error);
  final Object error;
}

const String _dbFileName = 'watchedledger.sqlite';
const String _keyName = 'watchedledger.db_key.v1';
const String _noCipherMarker = 'WL_NO_CIPHER';

const FlutterSecureStorage _secureStorage = FlutterSecureStorage(
  // Never synced to iCloud or migrated to another device; your own encrypted
  // backup files are how data moves between phones.
  iOptions: IOSOptions(
    accessibility: KeychainAccessibility.first_unlock_this_device,
  ),
);

Future<File> databaseFile() async {
  final dir = await getApplicationSupportDirectory();
  return File(p.join(dir.path, _dbFileName));
}

String _newKey() {
  final rnd = Random.secure();
  final bytes = List<int>.generate(32, (_) => rnd.nextInt(256));
  return bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
}

QueryExecutor _encryptedExecutor(File file, String hexKey) {
  // The key is generated by us and is hex only, so it is safe to inline.
  assert(RegExp(r'^[0-9a-f]{64}$').hasMatch(hexKey));
  return NativeDatabase.createInBackground(
    file,
    setup: (rawDb) {
      // Refuse to run without encryption rather than silently writing a
      // plain-text database.
      if (rawDb.select('PRAGMA cipher;').isEmpty) {
        throw StateError(
            '$_noCipherMarker: this build has no SQLite3MultipleCiphers support');
      }
      rawDb.execute("PRAGMA key = '$hexKey';");
      rawDb.execute('PRAGMA secure_delete = ON;');
    },
  );
}

Future<OpenResult> openAppDatabase() async {
  try {
    final file = await databaseFile();
    final exists = await file.exists();
    var key = await _secureStorage.read(key: _keyName);

    if (key == null) {
      if (exists) return DbKeyProblem(file, keyMissing: true);
      key = _newKey();
      await _secureStorage.write(key: _keyName, value: key);
    }

    final db = AppDatabase(_encryptedExecutor(file, key));
    try {
      // Forces the file open, the key check and any migrations.
      await db.customSelect('SELECT count(*) FROM sqlite_master').get();
    } catch (e) {
      await db.close();
      final msg = e.toString();
      if (msg.contains(_noCipherMarker)) return DbFailed(e);
      if (exists && msg.contains('not a database')) {
        return DbKeyProblem(file, keyMissing: false);
      }
      return DbFailed(e);
    }
    return DbOpened(db);
  } catch (e) {
    return DbFailed(e);
  }
}

/// Moves an unreadable database aside (never deletes it) and forgets the key,
/// so the app can start with an empty database.
Future<File> moveUnreadableDatabaseAside(File file) async {
  final stamp = DateTime.now().millisecondsSinceEpoch;
  final target = File(p.join(
    file.parent.path,
    'watchedledger.unreadable-$stamp.sqlite',
  ));
  await file.rename(target.path);
  for (final suffix in const ['-journal', '-wal', '-shm']) {
    final side = File('${file.path}$suffix');
    if (await side.exists()) {
      await side.rename('${target.path}$suffix');
    }
  }
  await _secureStorage.delete(key: _keyName);
  return target;
}
